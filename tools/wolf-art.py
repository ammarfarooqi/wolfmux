#!/usr/bin/env python3
"""wolf-art.py — the one source of the Wolfmux wolf.

The wolf is a small pixel drawing (left half below, mirrored). This script turns
it into everything that shows it, so the terminal, the README and the diagrams
always carry the same animal:

    tools/wolf-art.py ansi      half-block text with 256-colour codes  (terminal)
    tools/wolf-art.py plain     the same without colour                (NO_COLOR, pipes)
    tools/wolf-art.py svg       pixel logo                             (docs/diagrams/wolf.svg)
    tools/wolf-art.py icns      app icon for the notifier (config/wolfmux/notifier/Wolfmux.icns; needs macOS sips + iconutil)
    tools/wolf-art.py install   rewrite the generated block in config/wolfmux/lib/brand.sh,
                                docs/diagrams/wolf.svg, and the wolf inside any diagram that
                                carries the markers <!-- wolf:begin cell=N x=X y=Y --> … <!-- wolf:end -->

Two pixel rows become one text row (upper half block, lower half block), which is
why the drawing has an even number of rows. Python 3 standard library only.
"""
import os
import re
import struct
import subprocess
import sys
import tempfile
import zlib

# Left half, 18 columns; column 17 touches the centre line. Legend:
#   .  nothing      d  dark fur      m  mid fur      l  light fur
#   e  eye          n  nose
HALF = [
    "...d..............",
    "...dd.............",
    "..dddd............",
    "..ddmdd...........",
    "..dmmmdd..........",
    "..dmmmmdd.........",
    "..ddmmmddd....dddd",
    "..dddmmdddd.dddddd",
    "..dddddddddddddddd",
    "..dddddddddddddddd",
    ".ddddddddddddddddd",
    ".ddddddddddddddddd",
    ".dddddddddddddmmdd",
    "dddddddmeeeedmmmmd",
    ".dddddmmmeeeemmmmm",
    "dddddmmmmmmmmmmmmm",
    ".ddddmmmmmmmmllllm",
    "ddddmmmmmmmmllllll",
    "..dddmmmmmmlllllll",
    ".ddddmmmmmllllllll",
    "...dddmmmmllllllll",
    "..ddddmmmlllllllll",
    "....dddmmlllllllll",
    ".....ddmmlllllllll",
    "......ddmmllllllll",
    "........dmmlllllll",
    ".........dmmllllnn",
    "..........dmmllnnn",
    "...........dmmllnn",
    "............dmmlll",
    "..............dmml",
    "................dm",
]

# 256-colour indexes for the terminal, hex for SVG. Mid-tones on purpose: the
# banner must read on a white terminal as well as on a dark one.
TONES = {
    "d": (238, "#46505f"),
    "m": (245, "#8a94a6"),
    "l": (252, "#d3d9e4"),
    "e": (214, "#f5b942"),
    "n": (234, "#161b26"),
}
PLAIN_HOLES = {"e", "n"}  # without colour these stay empty so the face still reads

BEGIN = "# >>> generated by tools/wolf-art.py — do not edit by hand >>>"
END = "# <<< generated by tools/wolf-art.py <<<"


def pixels() -> list[str]:
    rows = [half + half[::-1] for half in HALF]
    width = len(rows[0])
    assert len(rows) % 2 == 0 and all(len(r) == width for r in rows), "bitmap must be even and rectangular"
    return rows


def ansi_lines(rows: list[str]) -> list[str]:
    out = []
    for top, bottom in zip(rows[0::2], rows[1::2]):
        line, current = "", None
        for t, b in zip(top, bottom):
            if t == "." and b == ".":
                style, char = None, " "
            elif b == ".":
                style, char = f"38;5;{TONES[t][0]}", "▀"
            elif t == ".":
                style, char = f"38;5;{TONES[b][0]}", "▄"
            elif t == b:
                style, char = f"38;5;{TONES[t][0]}", "█"
            else:
                style, char = f"38;5;{TONES[t][0]};48;5;{TONES[b][0]}", "▀"
            if style != current:
                line += "\033[0m" if style is None else f"\033[0;{style}m"
                current = style
            line += char
        out.append(line.rstrip(" ") + ("\033[0m" if current else ""))
    return out


def plain_lines(rows: list[str]) -> list[str]:
    out = []
    for top, bottom in zip(rows[0::2], rows[1::2]):
        line = ""
        for t, b in zip(top, bottom):
            t_on, b_on = t != "." and t not in PLAIN_HOLES, b != "." and b not in PLAIN_HOLES
            line += "█" if t_on and b_on else "▀" if t_on else "▄" if b_on else " "
        out.append(line.rstrip())
    return out


def svg_rects(rows: list[str], cell: int, left: int, top: int) -> list[str]:
    """One <rect> per horizontal run of equal pixels."""
    rects = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            tone = row[x]
            run = 1
            while x + run < len(row) and row[x + run] == tone:
                run += 1
            if tone != ".":
                rects.append(f'<rect x="{left + x * cell}" y="{top + y * cell}" width="{run * cell}" height="{cell}" fill="{TONES[tone][1]}"/>')
            x += run
    return rects


def svg(rows: list[str], cell: int = 10, pad: int = 20) -> str:
    width, height = len(rows[0]) * cell + 2 * pad, len(rows) * cell + 2 * pad
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}" role="img" aria-labelledby="t">',
        '<title id="t">Wolfmux wolf</title>',
        f'<rect width="{width}" height="{height}" rx="28" fill="#0b1020"/>',
        '<g shape-rendering="crispEdges">',
        *svg_rects(rows, cell, pad, pad),
        "</g>",
        "</svg>",
    ]
    return "\n".join(parts) + "\n"


WOLF_SLOT = re.compile(r"(<!-- wolf:begin cell=(\d+) x=(\d+) y=(\d+) -->).*?(<!-- wolf:end -->)", re.S)


def refresh_diagram(path: str, rows: list[str]) -> bool:
    """Redraw the wolf inside a hand-written diagram; True when the file carries a slot."""
    text = open(path, encoding="utf-8").read()

    def draw(match: re.Match) -> str:
        cell, left, top = int(match.group(2)), int(match.group(3)), int(match.group(4))
        body = "\n".join(svg_rects(rows, cell, left, top))
        return f'{match.group(1)}\n<g shape-rendering="crispEdges">\n{body}\n</g>\n{match.group(5)}'

    updated, count = WOLF_SLOT.subn(draw, text)
    if count and updated != text:
        open(path, "w", encoding="utf-8").write(updated)
    return count > 0


def hex_rgba(color: str) -> tuple[int, int, int, int]:
    return int(color[1:3], 16), int(color[3:5], 16), int(color[5:7], 16), 255


def icon_pixels(rows: list[str], size: int = 1024) -> list[bytearray]:
    """The wolf on a night-coloured rounded square, the shape macOS icons have."""
    margin, radius, cell = 100, 184, 20
    night, clear = hex_rgba("#0b1020"), (0, 0, 0, 0)
    inner = size - 2 * margin
    image = [bytearray(clear * size) for _ in range(size)]
    for y in range(margin, size - margin):
        for x in range(margin, size - margin):
            dx = max(margin + radius - x, 0, x - (size - margin - radius - 1))
            dy = max(margin + radius - y, 0, y - (size - margin - radius - 1))
            if dx * dx + dy * dy <= radius * radius:
                image[y][4 * x:4 * x + 4] = bytes(night)
    left = margin + (inner - len(rows[0]) * cell) // 2
    top = margin + (inner - len(rows) * cell) // 2
    for row_index, row in enumerate(rows):
        for column, tone in enumerate(row):
            if tone == ".":
                continue
            pixel = bytes(hex_rgba(TONES[tone][1]))
            for y in range(top + row_index * cell, top + (row_index + 1) * cell):
                image[y][4 * (left + column * cell):4 * (left + (column + 1) * cell)] = pixel * cell
    return image


def png_bytes(image: list[bytearray]) -> bytes:
    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    size = len(image)
    raw = b"".join(b"\x00" + bytes(row) for row in image)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def write_icns(rows: list[str]) -> None:
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    target = os.path.join(repo, "config", "wolfmux", "notifier", "Wolfmux.icns")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with tempfile.TemporaryDirectory() as work:
        master = os.path.join(work, "master.png")
        with open(master, "wb") as handle:
            handle.write(png_bytes(icon_pixels(rows)))
        iconset = os.path.join(work, "Wolfmux.iconset")
        os.makedirs(iconset)
        for points in (16, 32, 128, 256, 512):
            for scale in (1, 2):
                name = f"icon_{points}x{points}{'@2x' if scale == 2 else ''}.png"
                subprocess.run(["sips", "-z", str(points * scale), str(points * scale), master, "--out", os.path.join(iconset, name)], check=True, capture_output=True)
        subprocess.run(["iconutil", "-c", "icns", iconset, "-o", target], check=True)
    print(f"wrote {os.path.relpath(target, repo)}")


def brand_block(rows: list[str]) -> str:
    # The escape character is written as the four characters \033 and turned back by
    # printf %b, so brand.sh stays a plain text file without control bytes.
    ansi = "\n".join(line.replace("\033", "\\033") for line in ansi_lines(rows))
    plain = "\n".join(plain_lines(rows))
    return "\n".join([
        BEGIN,
        "_brand_wolf_ansi() {\n  local line\n  while IFS= read -r line; do printf '%b\\n' \"$line\"; done <<'WOLF'\n" + ansi + "\nWOLF\n}",
        "_brand_wolf_plain() {\n  /bin/cat <<'WOLF'\n" + plain + "\nWOLF\n}",
        END,
    ])


def install(rows: list[str]) -> None:
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(repo, "config", "wolfmux", "lib", "brand.sh")
    text = open(path, encoding="utf-8").read()
    start, stop = text.index(BEGIN), text.index(END) + len(END)
    open(path, "w", encoding="utf-8").write(text[:start] + brand_block(rows) + text[stop:])
    diagrams = os.path.join(repo, "docs", "diagrams")
    open(os.path.join(diagrams, "wolf.svg"), "w", encoding="utf-8").write(svg(rows))
    slots = [name for name in sorted(os.listdir(diagrams)) if name.endswith(".svg") and refresh_diagram(os.path.join(diagrams, name), rows)]
    print("updated config/wolfmux/lib/brand.sh, docs/diagrams/wolf.svg" + "".join(f", {name}" for name in slots))


def main() -> None:
    mode = sys.argv[1] if len(sys.argv) > 1 else "ansi"
    rows = pixels()
    if mode == "ansi":
        print("\n".join(ansi_lines(rows)))
    elif mode == "plain":
        print("\n".join(plain_lines(rows)))
    elif mode == "svg":
        sys.stdout.write(svg(rows))
    elif mode == "icns":
        write_icns(rows)
    elif mode == "install":
        install(rows)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
