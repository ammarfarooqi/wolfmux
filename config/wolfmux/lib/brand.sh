# brand_color_ok — colour only on a terminal that did not ask for none
brand_color_ok() { [ -t 1 ] && [ -z "${NO_COLOR:-}" ] && [ "${TERM:-dumb}" != "dumb" ]; }

# brand_wolf [indent] — the drawing, shifted right by <indent> columns
brand_wolf() {
  local indent="${1:-0}" pad line colored=0
  pad="$(printf '%*s' "$indent" '')"
  if brand_color_ok; then colored=1; fi # decided here: inside the pipe stdout is never a terminal
  if [ "$colored" -eq 1 ]; then _brand_wolf_ansi; else _brand_wolf_plain; fi |
    while IFS= read -r line; do printf '%s%s\n' "$pad" "$line"; done
}

# _brand_center <width> <text> [sgr] — one centred line, optionally styled
_brand_center() {
  local width="$1" text="$2" sgr="${3:-}" pad
  pad=$(((width - ${#text}) / 2))
  [ "$pad" -ge 0 ] || pad=0
  if [ -n "$sgr" ] && brand_color_ok; then
    printf '%*s\033[%sm%s\033[0m\n' "$pad" '' "$sgr" "$text"
  else
    printf '%*s%s\n' "$pad" '' "$text"
  fi
}

# _brand_team_line — "session · lead <model> · N workers" for the project in $PWD.
# Runs in a command substitution, so a `die` in here only ends that subshell.
_brand_team_line() {
  local role workers=0
  load_project
  reg_exists "$WOLFMUX_LEAD_ROLE" || return 1
  for role in $(reg_list); do
    if [ "$(reg_field "$role" kind)" = "worker" ]; then workers=$((workers + 1)); fi
  done
  printf '%s · lead %s · %d worker%s\n' "$(meta_get session)" "$(reg_field "$WOLFMUX_LEAD_ROLE" label)" \
    "$workers" "$([ "$workers" -eq 1 ] || printf s)"
}

# brand_banner — wolf and wordmark for a plain terminal (`teamctl start`)
brand_banner() {
  [ -t 1 ] || return 0 # never into a pipe, a log or an agent's tool output
  local width=$((WOLFMUX_WOLF_COLS + 4))
  printf '\n'
  brand_wolf 2
  printf '\n'
  _brand_center "$width" "W O L F M U X" "1;38;5;214"
  _brand_center "$width" "a pack of agents in tmux" "2"
  printf '\n'
}

# cmd_splash — internal (`teamctl _splash`): what the popup shows when a client
# attaches. Closes on any key, or by itself after WOLFMUX_SPLASH_SECONDS.
cmd_splash() {
  local seconds="${WOLFMUX_SPLASH_SECONDS:-3}" size rows cols spare team="" key
  case "$seconds" in "" | *[!0-9]*) seconds=3 ;; esac
  # tmux shrinks a popup that does not fit the terminal, so draw for the size we really got.
  size="$(stty size 2>/dev/null || true)"
  rows="${size%% *}"
  cols="${size##* }"
  case "$rows" in "" | *[!0-9]*) rows=$((WOLFMUX_SPLASH_HEIGHT - 2)) ;; esac
  case "$cols" in "" | *[!0-9]*) cols=$((WOLFMUX_SPLASH_WIDTH - 2)) ;; esac
  team="$(_brand_team_line 2>/dev/null)" || team=""

  spare=$((rows - 1)) # the final newline needs a row too, or the top scrolls away
  if [ "$spare" -ge "$WOLFMUX_WOLF_ROWS" ] && [ "$cols" -ge "$WOLFMUX_WOLF_COLS" ]; then
    spare=$((spare - WOLFMUX_WOLF_ROWS))
    [ "$spare" -lt 5 ] || printf '\n'
    brand_wolf $(((cols - WOLFMUX_WOLF_COLS) / 2))
    [ "$spare" -lt 4 ] || printf '\n'
  fi
  [ "$spare" -lt 1 ] || _brand_center "$cols" "W O L F M U X" "1;38;5;214"
  [ "$spare" -lt 2 ] || _brand_center "$cols" "a pack of agents in tmux" "2"
  if [ "$spare" -ge 3 ] && [ -n "$team" ]; then _brand_center "$cols" "$team" "38;5;245"; fi
  if [ -t 0 ]; then read -r -s -n 1 -t "$seconds" key || true; fi
  return 0
}
